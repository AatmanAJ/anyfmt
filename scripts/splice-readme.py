#!/usr/bin/env python3
"""Splice docs/FORMATS.md (generated from the capability registry) into README.md."""
import os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
table = open(os.path.join(root, "docs/FORMATS.md"), encoding="utf-8").read().strip()
table = table.replace("(MATRIX.md)", "(docs/MATRIX.md)")
path = os.path.join(root, "README.md")
readme = open(path, encoding="utf-8").read()
block = f"<!-- formats:start (generated by `make readme-formats`) -->\n{table}\n<!-- formats:end -->"
new, n = re.subn(r"<!-- formats:start.*?<!-- formats:end -->", block, readme, flags=re.S)
if n == 0:
    sys.exit("README.md has no formats markers")
open(path, "w", encoding="utf-8").write(new)
print("README format table updated")
